#!/usr/bin/env bash
# Re-downloads the third-party browser assets the Business Expenses example app
# serves from its own origin, into examples/business-expenses/public/vendor/.
#
# Why self-hosted: the example app used to load Bootstrap, Bootswatch,
# Bootstrap Icons and pdf.js from cdn.jsdelivr.net. A CDN link is not a
# dependency declaration, it is a request the holder's browser makes to someone
# else's server — so every page view of an identity demo handed jsDelivr the
# holder's IP address and the page they were on, and the app's cookie notice
# claimed no third party was involved while four files said otherwise. It also
# forced the Content Security Policy to admit a whole external origin for
# scripts, styles, fonts and workers, which is most of the policy's value gone
# to save assets we can serve ourselves. The platform does not do this (see
# scripts/fetch-fonts.sh and public/vendor/mediapipe); the example app had
# simply drifted.
#
# Versions are pinned here and nowhere else — the markup references unversioned
# paths, so an upgrade is a one-line edit in this file plus a re-run. The output
# is committed, because the deploy zip excludes node_modules and static assets
# must not depend on what the App Service build host decided to install.
#
# Needs network access, so it is a developer step, never part of a deploy.
set -Eeuo pipefail

BOOTSTRAP_VERSION="5.3.3"
BOOTSWATCH_VERSION="5.3.3"
BOOTSTRAP_ICONS_VERSION="1.11.3"
PDFJS_VERSION="4.10.38"

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
VENDOR_DIR="$ROOT_DIR/examples/business-expenses/public/vendor"
MANIFEST="$VENDOR_DIR/manifest.txt"

die() {
  printf '\nERROR: %s\n' "$*" >&2
  exit 1
}

command -v curl >/dev/null 2>&1 || die "curl is required"
command -v shasum >/dev/null 2>&1 || die "shasum is required"

# package@version <sp> remote path within the package <sp> local path under public/vendor
ASSETS=(
  "bootstrap@${BOOTSTRAP_VERSION} dist/js/bootstrap.bundle.min.js bootstrap/bootstrap.bundle.min.js"
  "bootswatch@${BOOTSWATCH_VERSION} dist/flatly/bootstrap.min.css bootstrap/bootstrap.flatly.min.css"
  "bootstrap-icons@${BOOTSTRAP_ICONS_VERSION} font/bootstrap-icons.min.css bootstrap-icons/bootstrap-icons.min.css"
  "bootstrap-icons@${BOOTSTRAP_ICONS_VERSION} font/fonts/bootstrap-icons.woff2 bootstrap-icons/fonts/bootstrap-icons.woff2"
  "bootstrap-icons@${BOOTSTRAP_ICONS_VERSION} font/fonts/bootstrap-icons.woff bootstrap-icons/fonts/bootstrap-icons.woff"
  "pdfjs-dist@${PDFJS_VERSION} build/pdf.min.mjs pdfjs/pdf.min.mjs"
  "pdfjs-dist@${PDFJS_VERSION} build/pdf.worker.min.mjs pdfjs/pdf.worker.min.mjs"
)

mkdir -p "$VENDOR_DIR"

printf '# Third-party assets served from this app'"'"'s own origin.\n' >"$MANIFEST.tmp"
printf '# Generated by scripts/fetch-example-vendor.sh — do not edit by hand.\n' >>"$MANIFEST.tmp"
printf '# bootstrap.flatly.min.css has its Google Fonts @import removed, so its\n' >>"$MANIFEST.tmp"
printf '# hash is of our copy rather than of the published file.\n' >>"$MANIFEST.tmp"
printf '# sha256  bytes  path  source\n' >>"$MANIFEST.tmp"

for asset in "${ASSETS[@]}"; do
  read -r package remote local <<<"$asset"
  url="https://cdn.jsdelivr.net/npm/${package}/${remote}"
  target="$VENDOR_DIR/$local"

  mkdir -p "$(dirname "$target")"
  printf 'Fetching %s\n' "$url"
  curl -fsSL "$url" -o "$target.part" || die "Download failed: $url"

  # A CDN that answers an unknown path with an HTML error page would otherwise
  # leave a file that looks downloaded and breaks only in the browser.
  [ -s "$target.part" ] || die "Empty download: $url"
  case "$local" in
    *.css|*.js|*.mjs)
      head -c 1 "$target.part" | grep -q '<' && die "Looks like an error page, not an asset: $url"
      ;;
  esac

  # Bootswatch themes open with `@import url(https://fonts.googleapis.com/...)`
  # for the theme's own typeface, so self-hosting the stylesheet while leaving
  # that line in would move the file and keep the third-party request —
  # Google Fonts instead of jsDelivr, and the one request on the critical path
  # because an @import blocks rendering. The app sets its own font-family from
  # self-hosted Inter and Saira in public/fonts.css and never used Lato, so the
  # line is removed rather than replaced.
  if [ "$local" = "bootstrap/bootstrap.flatly.min.css" ]; then
    perl -0pi -e 's{\@import url\(https://fonts\.googleapis\.com/[^)]*\);}{}g' "$target.part"
    if grep -q 'fonts\.googleapis\.com\|fonts\.gstatic\.com' "$target.part"; then
      die "Google Fonts reference survived in $local — the strip rule needs updating"
    fi
  fi

  mv "$target.part" "$target"
  sha="$(shasum -a 256 "$target" | awk '{print $1}')"
  bytes="$(wc -c <"$target" | tr -d ' ')"
  printf '%s  %s  %s  %s\n' "$sha" "$bytes" "$local" "$url" >>"$MANIFEST.tmp"
done

mv "$MANIFEST.tmp" "$MANIFEST"

printf '\nWrote %s\n' "${MANIFEST#"$ROOT_DIR"/}"
printf 'Vendored assets:\n'
sed -n '6,$p' "$MANIFEST" | awk '{printf "  %8s bytes  %s\n", $2, $3}'
printf '\nReferences to keep in step:\n'
printf '  examples/business-expenses/views/layouts/main.hbs  (CSS and JS tags)\n'
printf '  examples/business-expenses/public/signature.js      (pdf.js import and workerSrc)\n'
